/// <summary>A supplier invoice without merchandise (electricity, rent, transport) with its NCF and ITBIS. On credit it becomes a payable.</summary>
internal static class RecordExpense
{
    /// <param name="Id">Generated by the client (GUID v7): a retry returns the saved expense.</param>
    public sealed record Command(Guid SupplierId, string Ncf, DateOnly Date, string Description, ExpenseType Type, decimal Subtotal, decimal Itbis,
        PaymentTerms Terms, int? CreditDays = null, Guid? Id = null, SupplierPaymentMethod? Method = null, string? NcfOverrideReason = null) : ICommand<Response>;
    public sealed record Response(Guid Id, decimal Total);

    internal sealed class Validator : AbstractValidator<Command>
    {
        public Validator(TimeProvider clock)
        {
            RuleFor(c => c.Ncf).Must(Domain.Ncf.IsValid).WithMessage("El NCF no es válido (B01… de 11 caracteres o E31… de 13).");
            RuleFor(c => c.Date).Must(d => DocumentDate.IsValid(d, clock)).WithMessage(DocumentDate.Message);
            RuleFor(c => c.Description).NotEmpty().MaximumLength(150);
            RuleFor(c => c.Type).IsInEnum();
            RuleFor(c => c.Subtotal).GreaterThan(0).PrecisionScale(19, 2, true);
            RuleFor(c => c.Itbis).GreaterThanOrEqualTo(0).PrecisionScale(19, 2, true).LessThanOrEqualTo(c => c.Subtotal * 0.18m + 0.01m)
                .WithMessage("El ITBIS no puede pasar del 18 % del subtotal.");
            RuleFor(c => c.Terms).IsInEnum();
            RuleFor(c => c.Method).IsInEnum();
            RuleFor(c => c.CreditDays).InclusiveBetween(0, 365).When(c => c.CreditDays is not null);
            RuleFor(c => c.NcfOverrideReason).MaximumLength(DgiiNcfCheck.MaxReason);
        }
    }

    internal sealed class Handler(PurchasingDbContext db, IUserContext user, IAuditLog audit, TimeProvider clock, IDgiiPublicLookup dgii) : ICommandHandler<Command, Response>
    {
        public async Task<Result<Response>> Handle(Command c, CancellationToken ct)
        {
            var id = c.Id ?? Guid.CreateVersion7();
            if (await db.Expenses.AsNoTracking().FirstOrDefaultAsync(e => e.Id == id, ct) is { } saved) return new Response(saved.Id, saved.Total);
            var supplier = await db.Suppliers.AsNoTracking().FirstOrDefaultAsync(s => s.Id == c.SupplierId && s.IsActive, ct);
            if (supplier is null) return PurchasingErrors.SupplierNotFound;
            if (supplier.Rnc is null) return PurchasingErrors.SupplierWithoutRnc;
            var ncf = c.Ncf.Trim().ToUpperInvariant();
            if (await db.Expenses.AnyAsync(e => e.SupplierId == c.SupplierId && e.Ncf == ncf && !e.IsVoided, ct)
                || await db.Purchases.AnyAsync(x => x.SupplierId == c.SupplierId && x.Ncf == ncf && x.Status != PurchaseStatus.Voided, ct))
                return PurchasingErrors.DuplicateNcf;
            if (await DgiiNcfCheck.RefuseAsync(dgii, audit, supplier.Rnc, ncf, c.Date, c.NcfOverrideReason, "Expense", id, ct) is { } refused) return refused; // TK-252

            var expense = new Expense
            {
                Id = id, SupplierId = supplier.Id, SupplierName = supplier.Name, SupplierRnc = supplier.Rnc, Ncf = ncf, Date = c.Date,
                Description = c.Description.Trim(), Type = c.Type, Terms = c.Terms, Method = c.Terms == PaymentTerms.Cash ? c.Method : null,
                Subtotal = c.Subtotal, Itbis = c.Itbis, Total = c.Subtotal + c.Itbis,
                CreatedUtc = clock.GetUtcNow().UtcDateTime, UserId = user.UserId,
            };
            if (c.Terms == PaymentTerms.Credit)
            {
                expense.DueDate = c.Date.AddDays(c.CreditDays ?? supplier.CreditDays);
                db.Payables.Add(new Payable
                {
                    Id = Guid.CreateVersion7(), SupplierId = supplier.Id, Type = PayableDocumentType.Expense, DocumentId = expense.Id, Ncf = ncf,
                    Date = c.Date, DueDate = expense.DueDate.Value, Total = expense.Total,
                });
            }
            db.Expenses.Add(expense);
            await audit.RecordAsync("purchasing.record-expense", "Expense", expense.Id, c, ct);
            return new Response(expense.Id, expense.Total);
        }
    }

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app)
        {
            app.MapPost("/api/purchasing/expenses", async (Command c, ICommandHandler<Command, Response> h, CancellationToken ct) =>
                    (await h.Handle(c, ct)).ToHttp(r => Results.Created($"/api/purchasing/expenses/{r.Id}", r)))
                .RequirePermission(Permissions.PayablesPay).WithTags("Purchasing");
            app.MapGet("/api/purchasing/expenses", async (DateOnly from, DateOnly to, PurchasingDbContext db, CancellationToken ct) =>
                    Results.Ok(await db.Expenses.Where(e => e.Date >= from && e.Date <= to).OrderBy(e => e.Date).AsNoTracking().ToListAsync(ct)))
                .RequirePermission(Permissions.PayablesPay).WithTags("Purchasing");
        }
    }
}

/// <summary>Voids an expense typed wrong: it and its payable stop counting (and its NCF can be entered again). Not when it has payments.</summary>
internal static class VoidExpense
{
    public sealed record Command(Guid Id, string Reason) : ICommand<Ok>;

    internal sealed class Validator : AbstractValidator<Command>
    {
        public Validator() => RuleFor(c => c.Reason).NotEmpty().MaximumLength(200);
    }

    internal sealed class Handler(PurchasingDbContext db, IAuditLog audit) : ICommandHandler<Command, Ok>
    {
        public async Task<Result<Ok>> Handle(Command c, CancellationToken ct)
        {
            var supplierId = await db.Expenses.Where(e => e.Id == c.Id).Select(e => (Guid?)e.SupplierId).FirstOrDefaultAsync(ct);
            if (supplierId is null) return PurchasingErrors.ExpenseNotFound;
            await db.LockSupplierAsync(supplierId.Value, ct);
            var expense = await db.Expenses.SingleAsync(e => e.Id == c.Id, ct);
            if (expense.IsVoided) return PurchasingErrors.AlreadyVoided;
            var payable = await db.Payables.FirstOrDefaultAsync(x => x.DocumentId == expense.Id, ct);
            if (payable is not null && await db.HasPaymentsAsync(payable.Id, ct)) return PurchasingErrors.HasPayments;

            expense.IsVoided = true;
            expense.VoidReason = c.Reason.Trim();
            if (payable is not null) payable.IsVoided = true;
            await audit.RecordAsync("purchasing.void-expense", "Expense", expense.Id, new { expense.Ncf, expense.Total, c.Reason }, ct);
            return Ok.Value;
        }
    }

    internal sealed record Body(string Reason);

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app) =>
            app.MapPost("/api/purchasing/expenses/{id:guid}/void", async (Guid id, Body b, ICommandHandler<Command, Ok> h, CancellationToken ct) =>
                    (await h.Handle(new Command(id, b.Reason), ct)).ToHttp(_ => Results.NoContent()))
                .RequirePermission(Permissions.PayablesPay).WithTags("Purchasing");
    }
}

/// <summary>Pays a supplier. The amount goes to the oldest open invoices first (or to the ones chosen) and never beyond what is owed.
/// Cash taken from a register's drawer (<see cref="Command.ShiftId"/>) is also a withdrawal of that shift, so it needs register.withdraw or a supervisor.</summary>
internal static class PaySupplier
{
    /// <param name="SupplierPaymentId">Generated by the client (GUID v7): a retry returns the saved payment.</param>
    public sealed record Command(Guid SupplierId, decimal Amount, SupplierPaymentMethod Method, DateOnly Date, string? Reference = null,
        IReadOnlyList<Guid>? PayableIds = null, Guid? SupplierPaymentId = null, Guid? ShiftId = null, Guid? SupervisorApprovalId = null)
        : ICommand<Response>, IRequiresApproval
    {
        public string Permission => ShiftId is null ? Permissions.PayablesPay : Permissions.RegisterWithdraw;
        public Guid ResourceId => ShiftId ?? SupplierId;
    }

    public sealed record Allocated(Guid PayableId, string Ncf, decimal Amount, decimal RemainingBalance);
    public sealed record Response(Guid SupplierPaymentId, IReadOnlyList<Allocated> Allocations);

    internal sealed class Validator : AbstractValidator<Command>
    {
        public Validator(TimeProvider clock)
        {
            RuleFor(c => c.Amount).GreaterThan(0).PrecisionScale(19, 2, true);
            RuleFor(c => c.Amount).Must(m => m == Math.Truncate(m)).When(c => c.ShiftId is not null).WithMessage("El efectivo de la caja sale en pesos enteros.");
            RuleFor(c => c.Method).IsInEnum();
            RuleFor(c => c.Method).Equal(SupplierPaymentMethod.Cash).When(c => c.ShiftId is not null).WithMessage("De la caja solo sale efectivo.");
            RuleFor(c => c.Date).Must(d => DocumentDate.IsValid(d, clock)).WithMessage(DocumentDate.Message);
            RuleFor(c => c.Reference).MaximumLength(60);
        }
    }

    internal sealed class Handler(PurchasingDbContext db, ICashRegisterOperations register, IUserContext user, IOutbox outbox, IAuditLog audit, TimeProvider clock)
        : ICommandHandler<Command, Response>
    {
        public async Task<Result<Response>> Handle(Command c, CancellationToken ct)
        {
            var id = c.SupplierPaymentId ?? Guid.CreateVersion7();
            if (await SavedAsync(id, ct) is { } saved) return saved;
            // Lock order: shift → supplier → audit (the same as a sale: shift first).
            if (c.ShiftId is { } shiftId && await register.GetOpenShiftAsync(shiftId, ct) is { IsFailure: true } shift) return shift.Error!;
            if (await db.LockSupplierAsync(c.SupplierId, ct) == 0) return PurchasingErrors.SupplierNotFound;
            if (await SavedAsync(id, ct) is { } repeated) return repeated;

            var open = await db.OpenPayablesAsync(c.SupplierId, ct);
            if (c.PayableIds is { Count: > 0 } chosen) open = open.Where(a => chosen.Contains(a.Payable.Id)).ToList();
            if (c.Amount > open.Sum(a => a.Balance)) return PurchasingErrors.PaymentExceedsDebt;

            var payment = new SupplierPayment
            {
                Id = id, SupplierId = c.SupplierId, Date = c.Date, Amount = c.Amount, Method = c.Method, Reference = c.Reference?.Trim(), ShiftId = c.ShiftId,
                CreatedUtc = clock.GetUtcNow().UtcDateTime, UserId = user.UserId,
            };
            var allocated = Allocation.InOrder(c.Amount, open.Select(a => (a, a.Balance)))
                .Select(x => new Allocated(x.Item.Payable.Id, x.Item.Payable.Ncf, x.Amount, x.Item.Balance - x.Amount)).ToList();
            payment.Allocations.AddRange(allocated.Select(a => new PaymentAllocation { SupplierPaymentId = payment.Id, PayableId = a.PayableId, Amount = a.Amount }));
            if (c.ShiftId is { } shift2 && await register.RecordSupplierPaymentAsync(shift2, payment.Id, c.Amount, ct) is { IsFailure: true } inRegister) return inRegister.Error!;

            db.Payments.Add(payment);
            outbox.Add(new SupplierPaymentRecordedV1(payment.Id, c.SupplierId, c.Amount));
            await audit.RecordAsync("purchasing.pay-supplier", "Supplier", c.SupplierId, new { Payment = payment.Id, c.Amount, c.Method, c.Reference, c.ShiftId }, ct);
            return new Response(payment.Id, allocated);
        }

        private async Task<Response?> SavedAsync(Guid id, CancellationToken ct)
        {
            var payment = await db.Payments.Include(p => p.Allocations).AsNoTracking().FirstOrDefaultAsync(p => p.Id == id, ct);
            if (payment is null) return null;
            var ids = payment.Allocations.Select(a => a.PayableId).ToList();
            var ncfs = await db.Payables.Where(x => ids.Contains(x.Id)).ToDictionaryAsync(x => x.Id, x => x.Ncf, ct);
            return new Response(payment.Id, payment.Allocations.Select(a => new Allocated(a.PayableId, ncfs[a.PayableId], a.Amount, 0)).ToList());
        }
    }

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app) =>
            app.MapPost("/api/purchasing/payments", async (Command c, ICommandHandler<Command, Response> h, CancellationToken ct) =>
                    (await h.Handle(c, ct)).ToHttp())
                .RequirePermission(Permissions.PayablesPay).WithTags("Purchasing");
    }
}

/// <summary>Voids a supplier payment typed wrong: its invoices are open again. Cash taken from a drawer goes back into it (only while that shift is open).</summary>
internal static class VoidSupplierPayment
{
    public sealed record Command(Guid Id, string Reason) : ICommand<Ok>;

    internal sealed class Validator : AbstractValidator<Command>
    {
        public Validator() => RuleFor(c => c.Reason).NotEmpty().MaximumLength(200);
    }

    internal sealed class Handler(PurchasingDbContext db, ICashRegisterOperations register, IAuditLog audit) : ICommandHandler<Command, Ok>
    {
        public async Task<Result<Ok>> Handle(Command c, CancellationToken ct)
        {
            var data = await db.Payments.Where(p => p.Id == c.Id).Select(p => new { p.SupplierId, p.ShiftId }).FirstOrDefaultAsync(ct);
            if (data is null) return PurchasingErrors.PaymentNotFound;
            // Shift first (a failed reversal rolls back with the rest), then the supplier, where the state is checked again.
            if (data.ShiftId is not null && await register.VoidMovementsAsync(c.Id, ct) is { IsFailure: true } inRegister) return inRegister.Error!;
            await db.LockSupplierAsync(data.SupplierId, ct);
            var payment = await db.Payments.SingleAsync(p => p.Id == c.Id, ct);
            if (payment.IsVoided) return PurchasingErrors.AlreadyVoided;

            payment.IsVoided = true;
            payment.VoidReason = c.Reason.Trim();
            await audit.RecordAsync("purchasing.void-payment", "Supplier", payment.SupplierId, new { Payment = payment.Id, payment.Amount, c.Reason }, ct);
            return Ok.Value;
        }
    }

    internal sealed record Body(string Reason);

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app) =>
            app.MapPost("/api/purchasing/payments/{id:guid}/void", async (Guid id, Body b, ICommandHandler<Command, Ok> h, CancellationToken ct) =>
                    (await h.Handle(new Command(id, b.Reason), ct)).ToHttp(_ => Results.NoContent()))
                .RequirePermission(Permissions.PayablesPay).WithTags("Purchasing");
    }
}

/// <summary>Supplier statement: invoices and payments in date order with the running balance. Voided ones are left out.
/// Type and document texts are what the owner reads, so they stay in Spanish.</summary>
internal static class SupplierStatement
{
    /// <param name="PaymentId">Set on a payment line, so it can be voided from the statement.</param>
    public sealed record Line(DateOnly Date, string Type, string Document, decimal Charge, decimal Payment, decimal Balance, DateOnly? DueDate, Guid? PaymentId = null);
    public sealed record Response(Guid SupplierId, string Supplier, decimal Balance, IReadOnlyList<Line> Lines);

    private static string TypeText(PayableDocumentType type) => type == PayableDocumentType.Purchase ? "Compra" : "Gasto";

    private static string MethodText(SupplierPaymentMethod method) => method switch
    {
        SupplierPaymentMethod.Cash => "Efectivo",
        SupplierPaymentMethod.Transfer => "Transferencia",
        SupplierPaymentMethod.Check => "Cheque",
        _ => "Tarjeta",
    };

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app) =>
            app.MapGet("/api/purchasing/suppliers/{id:guid}/statement", async (Guid id, PurchasingDbContext db, CancellationToken ct) =>
                {
                    var s = await db.Suppliers.AsNoTracking().FirstOrDefaultAsync(x => x.Id == id, ct);
                    if (s is null) return EndpointExtensions.Problem(PurchasingErrors.SupplierNotFound);
                    var charges = (await db.Payables.Where(x => x.SupplierId == id && !x.IsVoided).AsNoTracking().ToListAsync(ct))
                        .Select(x => (x.Date, Order: 0, Type: TypeText(x.Type), Doc: x.Ncf, Charge: x.Total, Payment: 0m, DueDate: (DateOnly?)x.DueDate, PaymentId: (Guid?)null));
                    var payments = (await db.Payments.Where(p => p.SupplierId == id && !p.IsVoided).AsNoTracking().ToListAsync(ct))
                        .Select(p => (p.Date, Order: 1, Type: "Pago", Doc: p.Reference ?? MethodText(p.Method), Charge: 0m, Payment: p.Amount, DueDate: (DateOnly?)null, PaymentId: (Guid?)p.Id));
                    var balance = 0m;
                    var lines = charges.Concat(payments).OrderBy(m => m.Date).ThenBy(m => m.Order)
                        .Select(m => new Line(m.Date, m.Type, m.Doc, m.Charge, m.Payment, balance += m.Charge - m.Payment, m.DueDate, m.PaymentId)).ToList();
                    return Results.Ok(new Response(s.Id, s.Name, balance, lines));
                })
                .RequirePermission(Permissions.PurchasingManage).WithTags("Purchasing");
    }
}

/// <summary>Payables aged by due date (current, 1–30, 31–60, 61–90, over 90 days overdue) and the 606; served and exported by Reports.</summary>
internal sealed class PurchasingReports(PurchasingDbContext db, TimeProvider clock) : IPurchasingReports
{
    public async Task<IReadOnlyList<SupplierPayable>> PayablesAsync(CancellationToken ct)
    {
        var today = BusinessDay.Of(clock.GetUtcNow().UtcDateTime);
        var suppliers = await db.Suppliers.AsNoTracking().ToDictionaryAsync(s => s.Id, s => s.Name, ct);
        return (await db.OpenPayablesAsync(null, ct)).GroupBy(a => a.Payable.SupplierId).Select(g =>
        {
            decimal Range(int from, int to) => g.Where(a => today.DayNumber - a.Payable.DueDate.DayNumber is var d && d >= from && d <= to).Sum(a => a.Balance);
            return new SupplierPayable(g.Key, suppliers.GetValueOrDefault(g.Key, "?"), Range(int.MinValue, 0), Range(1, 30), Range(31, 60), Range(61, 90),
                Range(91, int.MaxValue), g.Sum(a => a.Balance));
        }).OrderByDescending(i => i.Total).ToList();
    }

    /// <remarks>shortcut: a credit invoice is reported as on credit (4) without its payment date, and a cash one with no recorded method
    /// leaves the payment form empty; "ITBIS llevado al costo" for exempt sales stays at zero. The accountant confirms one month before the pilot (R5 #3).</remarks>
    public async Task<IReadOnlyList<Report606Row>> Report606Async(DateOnly from, DateOnly to, CancellationToken ct)
    {
        static int? PaymentForm(PaymentTerms terms, SupplierPaymentMethod? method) => terms == PaymentTerms.Credit ? 4 : method switch
        {
            SupplierPaymentMethod.Cash => 1,
            SupplierPaymentMethod.Transfer or SupplierPaymentMethod.Check => 2,
            SupplierPaymentMethod.Card => 3,
            _ => null,
        };
        static Report606Row Row(string? rnc, int type, string ncf, DateOnly date, decimal services, decimal goods, decimal itbis, PaymentTerms terms, SupplierPaymentMethod? method) =>
            new(rnc, rnc?.Length == 11 ? 2 : 1, type, ncf, null, date, terms == PaymentTerms.Cash ? date : null, services, goods, services + goods, itbis,
                0, 0, 0, itbis, 0, null, 0, 0, 0, 0, 0, PaymentForm(terms, method));
        var purchases = await db.Purchases.Where(p => p.Status == PurchaseStatus.Posted && p.InvoiceDate >= from && p.InvoiceDate <= to)
            .Select(p => new { p.SupplierRnc, p.Ncf, p.InvoiceDate, p.Subtotal, p.Itbis, p.Terms, p.Method }).AsNoTracking().ToListAsync(ct);
        var expenses = await db.Expenses.Where(e => !e.IsVoided && e.Date >= from && e.Date <= to)
            .Select(e => new { e.SupplierRnc, e.Type, e.Ncf, e.Date, e.Subtotal, e.Itbis, e.Terms, e.Method }).AsNoTracking().ToListAsync(ct);
        // Merchandise is goods; services, rent and the like are services.
        static bool IsService(ExpenseType t) => t is ExpenseType.WorkSuppliesAndServices or ExpenseType.Leases;
        return purchases.Select(p => Row(p.SupplierRnc, (int)ExpenseType.CostOfSales, p.Ncf, p.InvoiceDate, 0, p.Subtotal, p.Itbis, p.Terms, p.Method))
            .Concat(expenses.Select(e => Row(e.SupplierRnc, (int)e.Type, e.Ncf, e.Date, IsService(e.Type) ? e.Subtotal : 0, IsService(e.Type) ? 0 : e.Subtotal, e.Itbis,
                e.Terms, e.Method)))
            .OrderBy(d => d.DocumentDate).ThenBy(d => d.Ncf, StringComparer.Ordinal).ToList();
    }
}
