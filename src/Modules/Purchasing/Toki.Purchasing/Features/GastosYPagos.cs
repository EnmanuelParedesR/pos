/// <summary>A supplier invoice without merchandise (electricity, rent, transport) with its NCF and ITBIS. On credit it becomes a payable.</summary>
internal static class RegistrarGasto
{
    /// <param name="Id">Generated by the client (GUID v7): a retry returns the saved expense.</param>
    public sealed record Command(Guid SuplidorId, string Ncf, DateOnly Fecha, string Concepto, TipoGasto Tipo, decimal Subtotal, decimal Itbis,
        Condicion Condicion, int? DiasCredito = null, Guid? Id = null, MedioPagoSuplidor? Medio = null) : ICommand<Response>;
    public sealed record Response(Guid Id, decimal Total);

    internal sealed class Validator : AbstractValidator<Command>
    {
        public Validator(TimeProvider reloj)
        {
            RuleFor(c => c.Ncf).Must(Domain.Ncf.EsValido).WithMessage("El NCF no es válido (B01… de 11 caracteres o E31… de 13).");
            RuleFor(c => c.Fecha).Must(f => FechaDocumento.EsValida(f, reloj)).WithMessage(FechaDocumento.Mensaje);
            RuleFor(c => c.Concepto).NotEmpty().MaximumLength(150);
            RuleFor(c => c.Tipo).IsInEnum();
            RuleFor(c => c.Subtotal).GreaterThan(0).PrecisionScale(19, 2, true);
            RuleFor(c => c.Itbis).GreaterThanOrEqualTo(0).PrecisionScale(19, 2, true).LessThanOrEqualTo(c => c.Subtotal * 0.18m + 0.01m)
                .WithMessage("El ITBIS no puede pasar del 18 % del subtotal.");
            RuleFor(c => c.Condicion).IsInEnum();
            RuleFor(c => c.Medio).IsInEnum();
            RuleFor(c => c.DiasCredito).InclusiveBetween(0, 365).When(c => c.DiasCredito is not null);
        }
    }

    internal sealed class Handler(ComprasDbContext db, IUserContext usuario, IAuditoria auditoria, TimeProvider reloj) : ICommandHandler<Command, Response>
    {
        public async Task<Result<Response>> Handle(Command c, CancellationToken ct)
        {
            var id = c.Id ?? Guid.CreateVersion7();
            if (await db.Gastos.AsNoTracking().FirstOrDefaultAsync(g => g.Id == id, ct) is { } ya) return new Response(ya.Id, ya.Total);
            var suplidor = await db.Suplidores.AsNoTracking().FirstOrDefaultAsync(s => s.Id == c.SuplidorId && s.Activo, ct);
            if (suplidor is null) return ComprasErrors.SuplidorNoEncontrado;
            if (suplidor.Rnc is null) return ComprasErrors.SuplidorSinRnc;
            var ncf = c.Ncf.Trim().ToUpperInvariant();
            if (await db.Gastos.AnyAsync(g => g.SuplidorId == c.SuplidorId && g.Ncf == ncf && !g.Anulado, ct)
                || await db.Compras.AnyAsync(x => x.SuplidorId == c.SuplidorId && x.Ncf == ncf && x.Estado != EstadoCompra.Anulada, ct))
                return ComprasErrors.NcfRepetido;

            var gasto = new Gasto
            {
                Id = id, SuplidorId = suplidor.Id, SuplidorNombre = suplidor.Nombre, RncSuplidor = suplidor.Rnc, Ncf = ncf, Fecha = c.Fecha,
                Concepto = c.Concepto.Trim(), Tipo = c.Tipo, Condicion = c.Condicion, Medio = c.Condicion == Condicion.Contado ? c.Medio : null,
                Subtotal = c.Subtotal, Itbis = c.Itbis, Total = c.Subtotal + c.Itbis,
                CreadoUtc = reloj.GetUtcNow().UtcDateTime, UsuarioId = usuario.UsuarioId,
            };
            if (c.Condicion == Condicion.Credito)
            {
                gasto.Vence = c.Fecha.AddDays(c.DiasCredito ?? suplidor.DiasCredito);
                db.CuentasPorPagar.Add(new CuentaPorPagar
                {
                    Id = Guid.CreateVersion7(), SuplidorId = suplidor.Id, Tipo = TipoDocumento.Gasto, DocumentoId = gasto.Id, Ncf = ncf,
                    Fecha = c.Fecha, Vence = gasto.Vence.Value, Total = gasto.Total,
                });
            }
            db.Gastos.Add(gasto);
            await auditoria.RegistrarAsync("compras.gasto", "Gasto", gasto.Id, c, ct);
            return new Response(gasto.Id, gasto.Total);
        }
    }

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app)
        {
            app.MapPost("/api/compras/gastos", async (Command c, ICommandHandler<Command, Response> h, CancellationToken ct) =>
                    (await h.Handle(c, ct)).ToHttp(r => Results.Created($"/api/compras/gastos/{r.Id}", r)))
                .RequirePermiso(Permisos.ComprasGestionar).WithTags("Compras");
            app.MapGet("/api/compras/gastos", async (DateOnly desde, DateOnly hasta, ComprasDbContext db, CancellationToken ct) =>
                    Results.Ok(await db.Gastos.Where(g => g.Fecha >= desde && g.Fecha <= hasta).OrderBy(g => g.Fecha).AsNoTracking().ToListAsync(ct)))
                .RequirePermiso(Permisos.ComprasGestionar).WithTags("Compras");
        }
    }
}

/// <summary>Voids an expense typed wrong: it and its payable stop counting (and its NCF can be entered again). Not when it has payments.</summary>
internal static class AnularGasto
{
    public sealed record Command(Guid Id, string Motivo) : ICommand<Ok>;

    internal sealed class Validator : AbstractValidator<Command>
    {
        public Validator() => RuleFor(c => c.Motivo).NotEmpty().MaximumLength(200);
    }

    internal sealed class Handler(ComprasDbContext db, IAuditoria auditoria) : ICommandHandler<Command, Ok>
    {
        public async Task<Result<Ok>> Handle(Command c, CancellationToken ct)
        {
            var suplidorId = await db.Gastos.Where(g => g.Id == c.Id).Select(g => (Guid?)g.SuplidorId).FirstOrDefaultAsync(ct);
            if (suplidorId is null) return ComprasErrors.GastoNoEncontrado;
            await db.BloquearSuplidorAsync(suplidorId.Value, ct);
            var gasto = await db.Gastos.SingleAsync(g => g.Id == c.Id, ct);
            if (gasto.Anulado) return ComprasErrors.YaAnulado;
            var cuenta = await db.CuentasPorPagar.FirstOrDefaultAsync(x => x.DocumentoId == gasto.Id, ct);
            if (cuenta is not null && await db.TienePagosAsync(cuenta.Id, ct)) return ComprasErrors.ConPagos;

            gasto.Anulado = true;
            gasto.MotivoAnulacion = c.Motivo.Trim();
            if (cuenta is not null) cuenta.Anulada = true;
            await auditoria.RegistrarAsync("compras.anular-gasto", "Gasto", gasto.Id, new { gasto.Ncf, gasto.Total, c.Motivo }, ct);
            return Ok.Valor;
        }
    }

    internal sealed record Body(string Motivo);

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app) =>
            app.MapPost("/api/compras/gastos/{id:guid}/anular", async (Guid id, Body b, ICommandHandler<Command, Ok> h, CancellationToken ct) =>
                    (await h.Handle(new Command(id, b.Motivo), ct)).ToHttp(_ => Results.NoContent()))
                .RequirePermiso(Permisos.ComprasGestionar).WithTags("Compras");
    }
}

/// <summary>Pays a supplier. The amount goes to the oldest open invoices first (or to the ones chosen) and never beyond what is owed.
/// Cash taken from a register's drawer (<see cref="Command.TurnoId"/>) is also a withdrawal of that shift, so it needs caja.retirar or a supervisor.</summary>
internal static class PagarSuplidor
{
    /// <param name="PagoId">Generated by the client (GUID v7): a retry returns the saved payment.</param>
    public sealed record Command(Guid SuplidorId, decimal Monto, MedioPagoSuplidor Medio, DateOnly Fecha, string? Referencia = null,
        IReadOnlyList<Guid>? Cuentas = null, Guid? PagoId = null, Guid? TurnoId = null, Guid? AutorizacionSupervisorId = null)
        : ICommand<Response>, IRequiereAutorizacion
    {
        public string Permiso => TurnoId is null ? Permisos.ComprasGestionar : Permisos.CajaRetirar;
        public Guid RecursoId => TurnoId ?? SuplidorId;
    }

    public sealed record Aplicado(Guid CuentaId, string Ncf, decimal Monto, decimal SaldoRestante);
    public sealed record Response(Guid PagoId, IReadOnlyList<Aplicado> Aplicaciones);

    internal sealed class Validator : AbstractValidator<Command>
    {
        public Validator(TimeProvider reloj)
        {
            RuleFor(c => c.Monto).GreaterThan(0).PrecisionScale(19, 2, true);
            RuleFor(c => c.Monto).Must(m => m == Math.Truncate(m)).When(c => c.TurnoId is not null).WithMessage("El efectivo de la caja sale en pesos enteros.");
            RuleFor(c => c.Medio).IsInEnum();
            RuleFor(c => c.Medio).Equal(MedioPagoSuplidor.Efectivo).When(c => c.TurnoId is not null).WithMessage("De la caja solo sale efectivo.");
            RuleFor(c => c.Fecha).Must(f => FechaDocumento.EsValida(f, reloj)).WithMessage(FechaDocumento.Mensaje);
            RuleFor(c => c.Referencia).MaximumLength(60);
        }
    }

    internal sealed class Handler(ComprasDbContext db, ICajaOperaciones caja, IUserContext usuario, IOutbox outbox, IAuditoria auditoria, TimeProvider reloj)
        : ICommandHandler<Command, Response>
    {
        public async Task<Result<Response>> Handle(Command c, CancellationToken ct)
        {
            var id = c.PagoId ?? Guid.CreateVersion7();
            if (await GuardadoAsync(id, ct) is { } ya) return ya;
            // Lock order: shift → supplier → audit (the same as a sale: shift first).
            if (c.TurnoId is { } turnoId && await caja.ObtenerTurnoAbiertoAsync(turnoId, ct) is { IsFailure: true } turno) return turno.Error!;
            if (await db.BloquearSuplidorAsync(c.SuplidorId, ct) == 0) return ComprasErrors.SuplidorNoEncontrado;
            if (await GuardadoAsync(id, ct) is { } repetido) return repetido;

            var abiertas = await db.AbiertasAsync(c.SuplidorId, ct);
            if (c.Cuentas is { Count: > 0 } elegidas) abiertas = abiertas.Where(a => elegidas.Contains(a.Cuenta.Id)).ToList();
            if (c.Monto > abiertas.Sum(a => a.Saldo)) return ComprasErrors.PagoMayorQueDeuda;

            var pago = new PagoSuplidor
            {
                Id = id, SuplidorId = c.SuplidorId, Fecha = c.Fecha, Monto = c.Monto, Medio = c.Medio, Referencia = c.Referencia?.Trim(), TurnoId = c.TurnoId,
                CreadoUtc = reloj.GetUtcNow().UtcDateTime, UsuarioId = usuario.UsuarioId,
            };
            var aplicados = Asignacion.EnOrden(c.Monto, abiertas.Select(a => (a, a.Saldo)))
                .Select(x => new Aplicado(x.Item.Cuenta.Id, x.Item.Cuenta.Ncf, x.Monto, x.Item.Saldo - x.Monto)).ToList();
            pago.Aplicaciones.AddRange(aplicados.Select(a => new AplicacionPago { PagoId = pago.Id, CuentaId = a.CuentaId, Monto = a.Monto }));
            if (c.TurnoId is { } turno2 && await caja.RegistrarPagoSuplidorAsync(turno2, pago.Id, c.Monto, ct) is { IsFailure: true } enCaja) return enCaja.Error!;

            db.Pagos.Add(pago);
            outbox.Agregar(new PagoSuplidorRegistradoV1(pago.Id, c.SuplidorId, c.Monto));
            await auditoria.RegistrarAsync("compras.pago-suplidor", "Suplidor", c.SuplidorId, new { Pago = pago.Id, c.Monto, c.Medio, c.Referencia, c.TurnoId }, ct);
            return new Response(pago.Id, aplicados);
        }

        private async Task<Response?> GuardadoAsync(Guid id, CancellationToken ct)
        {
            var pago = await db.Pagos.Include(p => p.Aplicaciones).AsNoTracking().FirstOrDefaultAsync(p => p.Id == id, ct);
            if (pago is null) return null;
            var ids = pago.Aplicaciones.Select(a => a.CuentaId).ToList();
            var ncfs = await db.CuentasPorPagar.Where(x => ids.Contains(x.Id)).ToDictionaryAsync(x => x.Id, x => x.Ncf, ct);
            return new Response(pago.Id, pago.Aplicaciones.Select(a => new Aplicado(a.CuentaId, ncfs[a.CuentaId], a.Monto, 0)).ToList());
        }
    }

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app) =>
            app.MapPost("/api/compras/pagos", async (Command c, ICommandHandler<Command, Response> h, CancellationToken ct) =>
                    (await h.Handle(c, ct)).ToHttp())
                .RequirePermiso(Permisos.ComprasGestionar).WithTags("Compras");
    }
}

/// <summary>Voids a supplier payment typed wrong: its invoices are open again. Cash taken from a drawer goes back into it (only while that shift is open).</summary>
internal static class AnularPagoSuplidor
{
    public sealed record Command(Guid Id, string Motivo) : ICommand<Ok>;

    internal sealed class Validator : AbstractValidator<Command>
    {
        public Validator() => RuleFor(c => c.Motivo).NotEmpty().MaximumLength(200);
    }

    internal sealed class Handler(ComprasDbContext db, ICajaOperaciones caja, IAuditoria auditoria) : ICommandHandler<Command, Ok>
    {
        public async Task<Result<Ok>> Handle(Command c, CancellationToken ct)
        {
            var datos = await db.Pagos.Where(p => p.Id == c.Id).Select(p => new { p.SuplidorId, p.TurnoId }).FirstOrDefaultAsync(ct);
            if (datos is null) return ComprasErrors.PagoNoEncontrado;
            // Shift first (a failed reversal rolls back with the rest), then the supplier, where the state is checked again.
            if (datos.TurnoId is not null && await caja.AnularMovimientosAsync(c.Id, ct) is { IsFailure: true } enCaja) return enCaja.Error!;
            await db.BloquearSuplidorAsync(datos.SuplidorId, ct);
            var pago = await db.Pagos.SingleAsync(p => p.Id == c.Id, ct);
            if (pago.Anulado) return ComprasErrors.YaAnulado;

            pago.Anulado = true;
            pago.MotivoAnulacion = c.Motivo.Trim();
            await auditoria.RegistrarAsync("compras.anular-pago", "Suplidor", pago.SuplidorId, new { Pago = pago.Id, pago.Monto, c.Motivo }, ct);
            return Ok.Valor;
        }
    }

    internal sealed record Body(string Motivo);

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app) =>
            app.MapPost("/api/compras/pagos/{id:guid}/anular", async (Guid id, Body b, ICommandHandler<Command, Ok> h, CancellationToken ct) =>
                    (await h.Handle(new Command(id, b.Motivo), ct)).ToHttp(_ => Results.NoContent()))
                .RequirePermiso(Permisos.ComprasGestionar).WithTags("Compras");
    }
}

/// <summary>Supplier statement: invoices and payments in date order with the running balance. Voided ones are left out.</summary>
internal static class EstadoCuentaSuplidor
{
    public sealed record Movimiento(DateOnly Fecha, string Tipo, string Documento, decimal Cargo, decimal Abono, decimal Saldo, DateOnly? Vence);
    public sealed record Response(Guid SuplidorId, string Suplidor, decimal Saldo, IReadOnlyList<Movimiento> Movimientos);

    internal sealed class Endpoint : IEndpoint
    {
        public void Map(IEndpointRouteBuilder app) =>
            app.MapGet("/api/compras/suplidores/{id:guid}/estado-cuenta", async (Guid id, ComprasDbContext db, CancellationToken ct) =>
                {
                    var s = await db.Suplidores.AsNoTracking().FirstOrDefaultAsync(x => x.Id == id, ct);
                    if (s is null) return EndpointExtensions.Problema(ComprasErrors.SuplidorNoEncontrado);
                    var cargos = (await db.CuentasPorPagar.Where(x => x.SuplidorId == id && !x.Anulada).AsNoTracking().ToListAsync(ct))
                        .Select(x => (x.Fecha, Orden: 0, Tipo: x.Tipo.ToString(), Doc: x.Ncf, Cargo: x.Total, Abono: 0m, Vence: (DateOnly?)x.Vence));
                    var abonos = (await db.Pagos.Where(p => p.SuplidorId == id && !p.Anulado).AsNoTracking().ToListAsync(ct))
                        .Select(p => (p.Fecha, Orden: 1, Tipo: "Pago", Doc: p.Referencia ?? p.Medio.ToString(), Cargo: 0m, Abono: p.Monto, Vence: (DateOnly?)null));
                    var saldo = 0m;
                    var movimientos = cargos.Concat(abonos).OrderBy(m => m.Fecha).ThenBy(m => m.Orden)
                        .Select(m => new Movimiento(m.Fecha, m.Tipo, m.Doc, m.Cargo, m.Abono, saldo += m.Cargo - m.Abono, m.Vence)).ToList();
                    return Results.Ok(new Response(s.Id, s.Nombre, saldo, movimientos));
                })
                .RequirePermiso(Permisos.ComprasGestionar).WithTags("Compras");
    }
}

/// <summary>Payables aged by due date (current, 1–30, 31–60, 61–90, over 90 days overdue) and the 606; served and exported by Reportes.</summary>
internal sealed class ComprasReportes(ComprasDbContext db, TimeProvider reloj) : IComprasReportes
{
    public async Task<IReadOnlyList<CuentaPorPagarSuplidor>> PorPagarAsync(CancellationToken ct)
    {
        var hoy = DiaNegocio.De(reloj.GetUtcNow().UtcDateTime);
        var suplidores = await db.Suplidores.AsNoTracking().ToDictionaryAsync(s => s.Id, s => s.Nombre, ct);
        return (await db.AbiertasAsync(null, ct)).GroupBy(a => a.Cuenta.SuplidorId).Select(g =>
        {
            decimal Rango(int desde, int hasta) => g.Where(a => hoy.DayNumber - a.Cuenta.Vence.DayNumber is var d && d >= desde && d <= hasta).Sum(a => a.Saldo);
            return new CuentaPorPagarSuplidor(g.Key, suplidores.GetValueOrDefault(g.Key, "?"), Rango(int.MinValue, 0), Rango(1, 30), Rango(31, 60), Rango(61, 90),
                Rango(91, int.MaxValue), g.Sum(a => a.Saldo));
        }).OrderByDescending(i => i.Total).ToList();
    }

    /// <remarks>shortcut: a credit invoice is reported as on credit (4) without its payment date, and a cash one with no recorded medium
    /// leaves the payment form empty; "ITBIS llevado al costo" for exempt sales stays at zero. The accountant confirms one month before the pilot (R5 #3).</remarks>
    public async Task<IReadOnlyList<Documento606>> Documentos606Async(DateOnly desde, DateOnly hasta, CancellationToken ct)
    {
        static int? FormaPago(Condicion condicion, MedioPagoSuplidor? medio) => condicion == Condicion.Credito ? 4 : medio switch
        {
            MedioPagoSuplidor.Efectivo => 1,
            MedioPagoSuplidor.Transferencia or MedioPagoSuplidor.Cheque => 2,
            MedioPagoSuplidor.Tarjeta => 3,
            _ => null,
        };
        static Documento606 Fila(string? rnc, int tipo, string ncf, DateOnly fecha, decimal servicios, decimal bienes, decimal itbis, Condicion condicion, MedioPagoSuplidor? medio) =>
            new(rnc, rnc?.Length == 11 ? 2 : 1, tipo, ncf, null, fecha, condicion == Condicion.Contado ? fecha : null, servicios, bienes, servicios + bienes, itbis,
                0, 0, 0, itbis, 0, null, 0, 0, 0, 0, 0, FormaPago(condicion, medio));
        var compras = await db.Compras.Where(c => c.Estado == EstadoCompra.Aplicada && c.FechaFactura >= desde && c.FechaFactura <= hasta)
            .Select(c => new { c.RncSuplidor, c.Ncf, c.FechaFactura, c.Subtotal, c.Itbis, c.Condicion, c.Medio }).AsNoTracking().ToListAsync(ct);
        var gastos = await db.Gastos.Where(g => !g.Anulado && g.Fecha >= desde && g.Fecha <= hasta)
            .Select(g => new { g.RncSuplidor, g.Tipo, g.Ncf, g.Fecha, g.Subtotal, g.Itbis, g.Condicion, g.Medio }).AsNoTracking().ToListAsync(ct);
        // Merchandise is goods; services, rent and the like are services.
        static bool EsServicio(TipoGasto t) => t is TipoGasto.TrabajosSuministrosServicios or TipoGasto.Arrendamientos;
        return compras.Select(c => Fila(c.RncSuplidor, (int)TipoGasto.CostoDeVenta, c.Ncf, c.FechaFactura, 0, c.Subtotal, c.Itbis, c.Condicion, c.Medio))
            .Concat(gastos.Select(g => Fila(g.RncSuplidor, (int)g.Tipo, g.Ncf, g.Fecha, EsServicio(g.Tipo) ? g.Subtotal : 0, EsServicio(g.Tipo) ? 0 : g.Subtotal, g.Itbis,
                g.Condicion, g.Medio)))
            .OrderBy(d => d.FechaComprobante).ThenBy(d => d.Ncf, StringComparer.Ordinal).ToList();
    }
}
